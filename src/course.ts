/**
 * The course map: every chapter, every planned lesson and every learning objective, written or not.
 *
 * Advanced Infinitesimal Calculus 2 as the Hebrew University taught it in the second year (course 80316,
 * חשבון אינפיניטסימלי מתקדם (2), Einstein Institute of Mathematics), following the syllabus the user chose:
 * Ruth Lawrence's course page, spring 2002 (תשס"ב), www.ma.huji.ac.il/~ruthel/courses/infimb02/, sheets 00
 * (course information), 50 and 51 (material covered). It has four parts:
 *   1. differential geometry of curves in ℝⁿ: smooth curve, arc length, tangent, curvature, osculating circle;
 *      signed curvature of plane curves and the curve recovered from it; Serret–Frenet, torsion, and the
 *      existence and uniqueness theorem;
 *   2. differential geometry of surfaces in ℝ³: smooth surface, normal and tangent plane, the fundamental forms
 *      Q₁ and Q₂, normal and geodesic curvature of a curve on a surface, geodesics, principal, Gauss and mean
 *      curvatures, elliptic / hyperbolic / parabolic / umbilic points, the Gauss map, minimal surfaces, the
 *      Theorema Egregium;
 *   3. integration on surfaces: change of variables (without proof), surface area, ∫ρ ds, ∫F·ds, ∬ρ dS, ∬F·dS,
 *      the meaning of a surface's curvature, grad / curl / div, Green, Stokes and Gauss (proved in easy cases),
 *      differential forms in two and three dimensions, dω, the general Stokes theorem;
 *   4. approximation theory: inner product spaces, projection onto a complete subspace or a closed convex set,
 *      Fourier series, Bessel, the space H[a,b], pointwise / uniform / mean convergence, Parseval, approximation
 *      by polynomials.
 * Chapters 1–10 follow that order. Chapter 0 gathers what the course assumes from Advanced Calculus 1 and
 * linear algebra. Lessons the syllabus does not name (2.5 Lancret, 8.6 closed and exact forms) are enrichment.
 * Chapter 11 (existence and uniqueness for ODEs) is beyond the 2002 syllabus, by the user's decision: it is marked
 * beyondSyllabus, rests on Advanced Calculus 1 (Banach's fixed point theorem, completeness of C[a,b], Arzelà–Ascoli)
 * and on lesson 0.6, and its lesson 11.5 (Peano) is enrichment.
 *
 * Objectives live here, not only in lesson front matter, so that the question banks of every chapter
 * can exist before its lessons are written: a student can practise a chapter from day one. A written
 * lesson must declare exactly the objectives listed here (lint-content checks it).
 *
 * Objective texts are plain text (lesson header, My Path, the test report): no TeX. A formula that
 * cannot be said in words is wrapped in U+2066 … U+2069 (LRI … PDI) with no-break spaces inside.
 */

export interface Objective {
  id: string;
  text: string;
}

export interface PlannedLesson {
  id: string;
  title: string;
  objectives: Objective[];
  /** a topic the 80316 syllabus does not name: the lesson is marked so, and no regular lesson uses it */
  enrichment?: boolean;
}

export interface Chapter {
  n: number;
  title: string;
  /** one line under the chapter title on the contents page */
  blurb: string;
  /** beyond the 80316 syllabus: labelled so on the contents page and in its lessons */
  beyondSyllabus?: boolean;
  lessons: PlannedLesson[];
}

/** Builds a lesson's objectives from their texts: OBJ-<lesson>-1, -2, … in order. */
const L = (id: string, title: string, texts: string[], extra: { enrichment?: boolean } = {}): PlannedLesson => ({
  id,
  title,
  objectives: texts.map((text, i) => ({ id: `OBJ-${id}-${i + 1}`, text })),
  ...extra,
});

